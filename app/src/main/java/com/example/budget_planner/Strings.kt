// shorthand to grab a translated string, falls back to the key itself if missing
fun t(tr: Map<String, String>, key: String, fallback: String = key) = tr[key] ?: fallback

// display name for a category key ("__unallocated__" is a virtual bucket)
fun catDisplay(name: String, tr: Map<String, String>) =
    if (name == "__unallocated__") t(tr, "unallocated") else name

